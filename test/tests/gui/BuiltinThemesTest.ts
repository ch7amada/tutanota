const SURFACES = [
	"surface",
	"surface_dim",
	"surface_bright",
	"surface_container_lowest",
	"surface_container_low",
	"surface_container",
	"surface_container_high",
	"surface_container_highest",
] as const satisfies ReadonlyArray<Role>
const ACCENTS = ["primary", "secondary", "tertiary", "error"] as const
const AAA = 7
const AA = 4.5

/**
 * [foreground, backgrounds, minimum contrast] for every pair that carries text or icons.
 *
 * Minimums are the WCAG level (AA 4.5:1 or AAA 7:1) the hand-tuned Mail themes before the Material 3 Expressive redesign reached
 * for the same pair, so that contrast is no worse than before; outline is non-text (3:1).
 * Order matters for {@link generateMailPalette}: accents are settled before their on-colors.
 */
function contrastFloors(isDark: boolean): Array<[Role, ReadonlyArray<Role>, number]> {
	return [
		...ACCENTS.map((accent): [Role, ReadonlyArray<Role>, number] => [accent, SURFACES, isDark ? AAA : AA]),
		["on_surface", SURFACES, AAA],
		["on_surface_variant", SURFACES, AAA],
		["inverse_on_surface", ["inverse_surface"], AAA],
		["inverse_primary", ["inverse_surface"], AA],
		...ACCENTS.flatMap(
			(accent): Array<[Role, ReadonlyArray<Role>, number]> => [
				[`on_${accent}`, [accent], isDark ? AAA : AA],
				[`on_${accent}_container`, [`${accent}_container`], AAA],
			],
		),
		...(["primary", "secondary", "tertiary"] as const).flatMap(
			(accent): Array<[Role, ReadonlyArray<Role>, number]> => [
				[`on_${accent}_fixed`, [`${accent}_fixed`, `${accent}_fixed_dim`], AAA],
				[`on_${accent}_fixed_variant`, [`${accent}_fixed`], AAA],
				[`on_${accent}_fixed_variant`, [`${accent}_fixed_dim`], AA],
			],
		),
		["outline", SURFACES.filter((s) => s !== "surface_dim"), 3],
	]
}

function minContrast(colors: Partial<Record<Role, string>>, fg: Role, bgs: ReadonlyArray<Role>): number {
	return Math.min(...bgs.map((bg) => contrast(colors[fg]!, colors[bg]!)))
}

/**
 * The recipe of the Mail palette baked into builtinThemes.ts (redesign ticket 03, candidate "A · Fidelity" of ticket 02).
 *
 * Material 3 Expressive scheme (library's 2025 spec, standard contrast) seeded from the Tuta logo red, with fidelity-style palettes:
 * the primary keeps the seed's chroma and primary_container is the seed itself. Then every text role that falls short of its
 * {@link contrastFloors} minimum is moved along its own tonal palette (keeping hue and chroma) until it reaches it.
 */
function generateMailPalette(isDark: boolean): Record<(typeof MAIL_PALETTE_ROLES)[number], string> {
	const seed = argbFromHex("#850122")
	const source = Hct.fromInt(seed)
	const core = CorePalette.contentOf(seed)
	const scheme = new DynamicScheme({
		sourceColorHct: source,
		contrastLevel: 0,
		isDark,
		primaryPalette: core.a1,
		secondaryPalette: TonalPalette.fromHueAndChroma(source.hue, Math.max(source.chroma - 32, source.chroma * 0.5)),
		tertiaryPalette: core.a3,
		// kept well below SchemeFidelity's chroma / 8 because the 2025 spec boosts neutral chroma for the containers
		neutralPalette: TonalPalette.fromHueAndChroma(source.hue, 5),
		neutralVariantPalette: TonalPalette.fromHueAndChroma(source.hue, 8),
	})
	const camelCase = (role: string) => role.replace(/_(\w)/g, (_, c: string) => c.toUpperCase())
	const colors = Object.fromEntries(
		MAIL_PALETTE_ROLES.map((role) => [role, hexFromArgb(downcast<Record<string, number>>(scheme)[camelCase(role)]).toUpperCase()]),
	) as Record<(typeof MAIL_PALETTE_ROLES)[number], string>

	// fidelity: the primary container is the logo red, its text the usual container tone (or whatever reaches 7:1)
	const lighter = Contrast.lighter(source.tone, 7)
	const onContainerTone = lighter >= 0 ? Math.max(lighter, 90) : Math.min(Contrast.darker(source.tone, 7), 10)
	colors.primary_container = hexFromArgb(scheme.primaryPalette.tone(source.tone)).toUpperCase()
	colors.on_primary_container = hexFromArgb(scheme.primaryPalette.tone(onContainerTone)).toUpperCase()

	const paletteOf = (role: Role): TonalPalette =>
		role.includes("primary")
			? scheme.primaryPalette
			: role.includes("secondary")
				? scheme.secondaryPalette
				: role.includes("tertiary")
					? scheme.tertiaryPalette
					: role.includes("error")
						? scheme.errorPalette
						: role.includes("variant") || role.startsWith("outline")
							? scheme.neutralVariantPalette
							: scheme.neutralPalette
	for (const [fg, bgs, min] of contrastFloors(isDark)) {
		const key = fg as (typeof MAIL_PALETTE_ROLES)[number]
		if (minContrast(colors, key, bgs) >= min) continue
		const fromTone = Hct.fromInt(argbFromHex(colors[key])).tone
		const step = Hct.fromInt(argbFromHex(colors[bgs[0] as (typeof MAIL_PALETTE_ROLES)[number]])).tone > fromTone ? -0.5 : 0.5
		let tone = Math.round(fromTone * 2) / 2
		while (minContrast(colors, key, bgs) < min) {
			tone += step
			if (tone < 0 || tone > 100) throw new Error(`${fg} cannot reach ${min}:1`)
			colors[key] = hexFromArgb(paletteOf(fg).tone(tone)).toUpperCase()
		}
	}
	return colors
}

o.spec("builtin themes", () => {
	for (const base of ["light", "dark"] as const) {
		o.spec(`Mail ${base}`, () => {
			const theme = () => themes()[base]

			o.test("Material 3 roles match the palette recipe", () => {
				const expected = generateMailPalette(base === "dark")
				for (const role of MAIL_PALETTE_ROLES) {
					o.check(`${role}: ${theme()[role].toUpperCase()}`).equals(`${role}: ${expected[role]}`)
				}
			})

			o.test("text and icon roles keep at least the contrast level of the previous themes", () => {
				for (const [fg, bgs, min] of contrastFloors(base === "dark")) {
					const ratio = minContrast(theme(), fg, bgs)
					o.check(ratio >= min).equals(true)(`${fg} on ${bgs.join(", ")}: ${ratio.toFixed(2)} < ${min}`)
				}
			})

			o.test("non-Material icon colors stay visible on the content surfaces (>= 3:1)", () => {
				const iconRoles = ["warning", "success", "drive_folder", "drive_document", "drive_image", "drive_video", "drive_audio"] as const
				for (const fg of iconRoles) {
					const ratio = minContrast(
						theme(),
						fg,
						SURFACES.filter((s) => s !== "surface_dim"),
					)
					o.check(ratio >= 3).equals(true)(`${fg}: ${ratio.toFixed(2)}`)
				}
				o.check(minContrast(theme(), "on_warning_container", ["warning_container"]) >= AA).equals(true)
				o.check(minContrast(theme(), "on_success_container", ["success_container"]) >= AA).equals(true)
			})
		})
	}

	o.test("added roles of the blue themes follow the whitelabel fallback rules", () => {
		const addedRoles = [
			"inverse_primary",
			"surface_dim",
			"surface_bright",
			"surface_container_lowest",
			"surface_container_low",
			"inverse_surface",
			"inverse_on_surface",
			"shadow",
		] as const
		for (const themeId of ["light_secondary", "dark_secondary"] as const) {
			const theme = themes()[themeId]
			const withoutAddedRoles: Partial<Theme> = { ...theme }
			for (const role of addedRoles) delete withoutAddedRoles[role]
			const derived = fillMissingColorRoles(withoutAddedRoles as Theme, withoutAddedRoles)
			for (const role of addedRoles) {
				o.check(`${themeId} ${role}: ${derived[role].toUpperCase()}`).equals(`${themeId} ${role}: ${theme[role].toUpperCase()}`)
			}
		}
	})
})

o.spec("fillMissingColorRoles", () => {
	const base = () => themes().light

	o.test("derives missing roles from customized colors instead of keeping the base theme's", () => {
		const customizations: Partial<Theme> = { primary: "#0040ff", surface: "#ffffff", surface_container: "#eeeeee", on_surface: "#111111" }
		const theme = fillMissingColorRoles({ ...base(), ...customizations }, customizations)
		o.check(theme.surface_container_low).equals("#f7f7f7")
		o.check(theme.surface_container_lowest).equals("#ffffff")
		o.check(theme.inverse_surface).equals("#111111")
		o.check(theme.inverse_on_surface).equals("#eeeeee")
		o.check(theme.inverse_primary).equals("#80a0ff")
	})

	o.test("keeps base roles whose sources were not customized and roles that were customized", () => {
		const customizations: Partial<Theme> = { primary: "#0040ff", inverse_primary: "#123456" }
		const theme = fillMissingColorRoles({ ...base(), ...customizations }, customizations)
		o.check(theme.inverse_primary).equals("#123456")
		o.check(theme.surface_container_low).equals(base().surface_container_low)
		o.check(theme.surface_dim).equals(base().surface_dim)
	})

	o.test("fills roles missing from a complete old theme, dark", () => {
		const oldTheme = downcast<Theme>({
			themeId: "old",
			surface: "#181212",
			surface_container: "#241e1e",
			surface_container_highest: "#3d3434",
			on_surface: "#f3ecec",
			primary: "#ffb3b5",
		})
		const theme = fillMissingColorRoles(oldTheme, oldTheme)
		o.check(theme.surface_container_lowest).equals("#0c0909")
		o.check(theme.surface_dim).equals("#181212")
		o.check(theme.surface_bright).equals("#463d3d")
		o.check(theme.shadow).equals("#000000")
	})

	o.test("does not throw on invalid colors and leaves the affected roles alone", () => {
		const customizations: Partial<Theme> = { surface: "not a color", primary: "#12" }
		o.check(fillMissingColorRoles({ ...base(), ...customizations }, customizations).surface_container_low).equals(base().surface_container_low)
		const valid: Partial<Theme> = { surface: "#ffffff", primary: "#12" }
		o.check(fillMissingColorRoles({ ...base(), ...valid }, valid).inverse_primary).equals(base().inverse_primary)
	})
})
